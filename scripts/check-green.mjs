import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'

const base = process.env.GREEN_TEST_URL || 'http://127.0.0.1:3004'
const browser = await chromium.launch()
const errors = []
try {
  const page = await browser.newPage()
  page.on('pageerror', error => errors.push(error.message))
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 960 })
    for (const route of ['/', '/band/', '/termine/', '/media/', '/booking/', '/musik/', '/kontakt/', '/impressum/', '/datenschutz/']) {
      const response = await page.goto(base + route, { waitUntil: 'networkidle' })
      assert.equal(response.status(), 200, `${route} bei ${width}px`)
      assert.equal(await page.locator('main h1').count(), 1, `${route}: genau eine Hauptüberschrift`)
      const headings = await page.locator('main h1, main h2, main h3').allTextContents()
      assert(headings.every(text => !/^\s*(?:\d+\s*[/–—-]|[/–—-])/.test(text)), `${route}: keine Kapitelmarker`)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${route}: kein Überlauf bei ${width}px`)
      for (const image of await page.locator('main img').all()) {
        await image.scrollIntoViewIfNeeded()
        await image.evaluate(img => img.decode())
        assert(await image.evaluate(img => img.naturalWidth > 0), `${route}: Bild geladen`)
      }
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base + '/', { waitUntil: 'networkidle' })
  assert.deepEqual(await page.locator('.desktop-nav a').allTextContents(), ['Band & Musik', 'Termine', 'Media'])
  assert.equal(await page.locator('.header-cta').innerText(), 'Buch uns')
  assert.match(await page.locator('.green-hero-title').innerText(), /^Wenn die\s*Polka\s*Salsa tanzt$/i)
  assert.equal(await page.locator('.concept-hero-copy h1 em').count(), 0, 'Kein separater BlechRegen-Schriftzug')
  assert.equal(await page.locator('.concept-facts, .concept-eyebrow, .concept-sticker').count(), 0)
  assert.equal(await page.locator('#musik .concept-genres article').count(), 3, 'Frühere Musikkarten erhalten')
  assert((await page.locator('#kapelle .concept-members article').count()) > 0, 'Besetzung wieder als Kacheln')
  assert.deepEqual(await page.locator('main > section[id]').evaluateAll(sections => sections.map(section => section.id)), ['geschichte', 'musik', 'kapelle', 'termine', 'booking'], 'Bisherige Startseitenabschnitte bleiben erhalten')
  assert.match(await page.locator('#geschichte').innerText(), /Bockbieranstich/)
  assert.match(await page.locator('#geschichte h2').textContent(), /Erst a Maß\.\s*Dann a Idee\./)
  assert.equal(await page.locator('#geschichte .home-story-poster').count(), 1)
  assert.equal(await page.locator('#geschichte p').count(), 2, 'Kurzer Einstieg; ausführliche Geschichte auf der Bandseite')
  assert.match(await page.locator('#musik').innerText(), /Eigene Arrangements/i)
  assert.equal(await page.locator('.concept-ticker button').count(), 0, 'Kein Pause-Button im Banner')
  await page.locator('.concept-ticker').focus()
  assert.equal(await page.locator('.ticker-track').evaluate(el => getComputedStyle(el).animationPlayState), 'paused')
  await page.locator('.brand').focus()
  await page.mouse.move(0, 0)
  assert.equal(await page.locator('.ticker-track').evaluate(el => getComputedStyle(el).animationPlayState), 'running')
  await page.screenshot({ path: '/tmp/blechregen-green-desktop.png', fullPage: true })
  await page.goto(base + '/band/', { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Mehr Latin', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Mehr Latin', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.match(await page.locator('output').innerText(), /Cumbia/)
  await page.screenshot({ path: '/tmp/blechregen-green-band.png', fullPage: true })
  await page.goto(base + '/booking/', { waitUntil: 'networkidle' })
  assert.equal(await page.locator('form[action^="mailto:"]').count(), 0)
  await page.getByLabel('Name / Organisation').fill('Lokaler Test')
  await page.getByLabel('E-Mail', { exact: true }).fill('test@example.invalid')
  await page.getByLabel('Was plant ihr?').fill('Nur Vorschau, nicht absenden.')
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__copied = text } } }))
  await page.getByRole('button', { name: 'Text kopieren', exact: true }).click()
  assert.match(await page.locator('[role="status"]').innerText(), /kopiert/)
  assert.match(await page.evaluate(() => window.__copied), /Lokaler Test/)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Nicht verfügbar') } } }))
  await page.getByRole('button', { name: 'Text kopieren', exact: true }).click()
  assert.match(await page.getByLabel('Text zum Kopieren').inputValue(), /Lokaler Test/)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(base + '/', { waitUntil: 'networkidle' })
  await page.locator('.mobile-menu summary').click()
  assert.deepEqual(await page.locator('.mobile-menu nav a').allTextContents(), ['Band & Musik', 'Termine', 'Media', 'Buch uns'])
  await page.locator('.mobile-menu nav a').first().click()
  await page.waitForURL('**/band/')
  assert.equal(await page.locator('.mobile-menu').getAttribute('open'), null, 'Menü schließt nach Navigation')
  await page.screenshot({ path: '/tmp/blechregen-green-mobile.png', fullPage: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(base + '/', { waitUntil: 'networkidle' })
  assert.equal(await page.locator('.ticker-track').evaluate(el => getComputedStyle(el).animationName), 'none')
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  const noJs = await browser.newPage({ javaScriptEnabled: false })
  await noJs.goto(base + '/booking/')
  assert.notEqual(await noJs.locator('fieldset').getAttribute('disabled'), null, 'Ohne JavaScript kein versehentlicher Formularversand')
  assert(await noJs.getByRole('button', { name: 'E-Mail-Entwurf öffnen' }).isDisabled())
  assert(await noJs.locator('noscript a').isVisible(), 'E-Mail-Alternative ohne JavaScript')
  assert.deepEqual(errors, [], 'Keine JavaScript-Laufzeitfehler')
  console.log('Grünes Design geprüft: 9 Seiten × 4 Breiten, Bilder, Navigation, Stil-Mix, Laufband, reduzierte Bewegung und Anfrage-Kopierfunktion. Keine Nachricht versendet.')
} finally {
  await browser.close()
}
